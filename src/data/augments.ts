import type { AugmentDef, DamageType, GlobalKey, ModifierDef, StatKey, TowerId, TowerTag } from './types';

const all = (stat: StatKey, pct?: number, add?: number): ModifierDef => ({ target: 'tower', scope: { kind: 'all' }, stat, pct, add });
const dmgType = (type: DamageType, stat: StatKey, pct?: number, add?: number): ModifierDef => ({
  target: 'tower',
  scope: { kind: 'damageType', type },
  stat,
  pct,
  add,
});
const tag = (t: TowerTag, stat: StatKey, pct?: number, add?: number): ModifierDef => ({
  target: 'tower',
  scope: { kind: 'tag', tag: t },
  stat,
  pct,
  add,
});
const tower = (id: TowerId, stat: StatKey, pct?: number, add?: number): ModifierDef => ({
  target: 'tower',
  scope: { kind: 'tower', tower: id },
  stat,
  pct,
  add,
});
const glob = (stat: GlobalKey, add: number): ModifierDef => ({ target: 'global', stat, add });

